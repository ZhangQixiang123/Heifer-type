    NormalReturn (res_eq (binop TCons x1 x2), EmptyHeap)
  | "^", [x1; x2] ->
    NormalReturn (res_eq (binop SConcat x1 x2), EmptyHeap)
  | "string_of_int", [x1] ->
    NormalReturn (res_eq (term (TApp ("string_of_int", [x1])) TyString), EmptyHeap)
  | _ ->
    failwith (Format.asprintf "unknown primitive: %s, args: %s" fname (string_of_list string_of_term actualArgs))  

let check_subtyps t_l t_r right post= 
     let t1 = get_type_from_terms t_l.term_desc in 
     let t2 = get_type_from_terms t_r.term_desc in 
    let r = 
                   try 
                   is_subtype t1 t2 
                   with Unification (_a,b) -> ( right := unify_var_name_in_state b t_l !right; post := unify_var_name_in_state b t_l !post; true)
                   in 
                   r
let remove_from_residue_kappa (f:pi*kappa) (t:kappa) = 
  let rec remove kappa =
  match (kappa,t) with
  | (PointsTo (a,b),PointsTo (c,_d)) -> if (a=c)  then  EmptyHeap else PointsTo (a,b)
  | (SepConj (a,b),_) -> SepConj (remove a, remove b) 
  | _ -> kappa
  in
  let new_kappa = remove (snd f) in 
  (fst f, new_kappa)


let entail_type (left_ori:pi*kappa) (right_ori:staged_spec) mapping = 
  let (req, ens) = find_pre_post right_ori in
  let post = ref ens in

  let left = ref left_ori in
  let right = ref req in
  let remove_list_1 = ref [] in
  let remove_list_2 = ref [] in
  let rec check_local maplist=
  match maplist with
  | [] -> (true)

  | (a,p) :: xs -> 
                   let type_term_l =  (find_in_state a !left) in 
                   try 
                   let type_term_r =  (find_in_state p !right) in 
                   

                   (match (type_term_l,type_term_r) with 
                   | (("s",t1),("s",t2)) -> let res = check_subtyps (snd t1) (snd t2) right post in 
                   if res then res && check_local xs else false
                   |(("h",t1),("h",t2)) -> let res = check_subtyps (snd t1) (snd t2) right post in 
                   if res then (remove_list_1 := t1::!remove_list_1;remove_list_2 := t2::!remove_list_2; (res && check_local xs)) else false
                   | _ -> failwith "to be implemented"
                   ) 
                  with Stateerror _ ->  (true && check_local xs) 
                  in 
  let process_one =check_local mapping in 
  if not process_one then raise (Entailfail "entail fail in process one")
  else       
  let residue = List.fold_right (fun x acc-> remove_from_residue_kappa acc (PointsTo (fst x,snd x))) !remove_list_1 !left in 
  left := residue; 
  let remaining_frame = List.fold_right (fun x acc-> remove_from_residue_kappa acc (PointsTo (fst x,snd x))) !remove_list_2 !right in 
  let remove_list_3 = ref [] in  
  let rec check_remaining f =
    match f with
    |SepConj (a,b) -> check_remaining a && check_remaining b
    | EmptyHeap -> true
    | PointsTo (a,b) -> let r = find_in_state a !left in
                        if (fst r) = "s" then false else if (PointsTo (a,b) = PointsTo (fst (snd r), snd (snd r))) then (remove_list_3 := (snd r)::!remove_list_3;true) else false
    | RecordPointsTo (a, fields) ->
        (* For record points-to, check if we can find a matching record in the left state *)
        let r = find_in_state a !left in
        if (fst r) = "s" then false
        else
          (* Check if the found record matches *)
          let found_term = snd (snd r) in
          (match found_term.term_desc with
           | TRecordTerm found_fields ->
               if List.length fields = List.length found_fields &&
                  List.for_all2 (fun (n1, t1) (n2, t2) -> n1 = n2 && t1 = t2) fields found_fields
               then (remove_list_3 := (snd r)::!remove_list_3; true)
               else false
           | _ -> false)
    in 
  let entail_result = check_remaining (snd remaining_frame) in 
  let final_residue = List.fold_right (fun x acc-> remove_from_residue_kappa acc (PointsTo (fst x,snd x))) !remove_list_3 !left in 
  if entail_result then (final_residue, !post) else failwith "entail fail in remaining"

let rec arg_mapping l1 l2 = match (l1,l2) with 
            |(x::xs,y::ys) -> (x,y)::(arg_mapping xs ys)
            |([],[]) -> []
            |_ -> failwith "parameter lists length not match"

let make_post post = 
  match post with 
  | NormalReturn (a,b) -> Sequence (Require (a,b), NormalReturn (a,b))
  | _ -> failwith "invalid post"

let make_post_state post= 
  match post with 
  | NormalReturn (a,b) -> (a,b)
  | Require (a,b) -> (a,b)
  | _ -> failwith "invalid post state"

let rec make_list_map list = 
  match  list with
  | [] -> []
  | x::xs -> (x,x) :: make_list_map xs

