                                let (r1,r2) = match_constructors xs ys s in
                                (true&&r1, r2)
    | (_x::_xs,[]) -> failwith "uneven parameter"
    | ([],_y::_ys) 
      -> failwith "uneven parameter"
    | _ -> failwith "to be implemented"

                                         

  
let match_type_with_pattern term s pattern = 
  let ty =  (snd (snd term)) in
  match (ty.term_desc,pattern.pattern_desc) with
  |(_, PVar x) -> if (fst term) = "s" then (true,(And (Colon (fst x,ty), fst s), snd s)) 
                  else (true,(And (Atomic (EQ,{term_desc=Var (fst x);term_type=pattern.pattern_type},{term_desc=Var (fst (snd term));term_type=pattern.pattern_type}), fst s), snd s))
  |(Type (BaseTy (Defty (a,b))),PConstr (c,d)) -> 
    if (a=c) then  
      let p_list = List.fold_right (fun x acc ->acc@[x.pattern_desc]) d [] in
      let r = match_constructors b p_list s in 
      if (fst r) then (true, (snd r)) else (false,s)
      else (false,s)
  |(Type TAny, PAny) -> (true,s)
  |_ ->  (false,s)
let choose_case_for_match s var cases = 
  let ty = (find_in_state var s) in
  let rec case_matching  cases_list = match cases_list with 
            | [] -> raise (Nomatch)
            | x :: xs -> let result = match_type_with_pattern ty s x.ccase_pat in 
                         if fst result then (x.ccase_expr, snd result) else case_matching xs in 
  case_matching cases  

let rec get_type_for_var var pi = 
  (* print_endline (string_of_pi pi); *)
 
  match pi with
  | Colon (x,v) -> if var = x then ( Some v) else None 
  | And (a,b) -> let r =  get_type_for_var var a in
                if  (r = None) then get_type_for_var var b else r 
  | _ -> None  

let rec process_args (x:ty list) pi= 
  match x with 
  | [] -> []
  | y::ys -> match y with 
            |  BaseTy (Tvar v) -> let r = get_type_for_var v pi in (match r with |None -> y::process_args ys pi | Some t -> (get_type_from_terms t.term_desc)::process_args ys pi )
            | BaseTy (Defty (g,b)) -> BaseTy (Defty (g,process_args b pi)) :: process_args ys pi 
            | _ -> y::process_args ys pi 

let rec normal_term term pi =
  let helper term r = (match r with 
                              |Some t -> t 
                              |None -> term) in 
  match term.term_desc with 
  | Type (BaseTy (Tvar x)) -> let r = get_type_for_var x pi in helper term r 
                              
  | Type (BaseTy (Defty (i,a))) -> 
                                                                                    let normal_list = List.fold_right (fun y acc -> (
                                                                                    match y with | BaseTy (Tvar x) -> let r = get_type_for_var x pi in (match r with
                                                                                                                                             | None -> acc@[y]
                                                                                                                                             | Some t -> acc@[get_type_from_terms t.term_desc])
                                                                                    | BaseTy (Defty (g,b)) -> acc@[BaseTy (Defty (g, process_args b pi))]
                                                                                    | _ -> acc@[y]  )) a [] in 
                                                                                    {term_type=term.term_type;term_desc = Type (BaseTy (Defty (i,normal_list)))}
  | _ -> term

